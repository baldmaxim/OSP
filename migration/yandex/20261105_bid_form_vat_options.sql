-- Файл 20261102 уже применён, и журнал сверяет его сумму: править тот файл нельзя.
-- Список вставлялся только в пустую таблицу, поэтому уже заведённое поле обновляется здесь.
-- Меняется только исходный список. Свой список администратора не трогаем.
-- Уже сохранённые ответы анкет не переписываются.

UPDATE public.bid_form_fields
SET options = '["22 %", "7 %", "5 %", "0 %"]'::jsonb,
    updated_at = now()
WHERE code = 'vat'
  AND options = '["22 %", "20 %", "10 %", "7 %", "5 %", "0 %", "Без НДС"]'::jsonb;
