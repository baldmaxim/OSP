-- колонка той же таблицы work_types — правила по строкам и список шлюза не меняются.
--  • division — коды подразделений ВОР (как tenders.vor_division, contracts.division, dc_requests.division), NULL — не указано;
--  • подразделения контрагента — подразделения его видов работ (своего поля у контрагента нет).
-- Только добавление и начальное распределение там, где подразделение не указано; повтор безопасен.
ALTER TABLE public.work_types ADD COLUMN IF NOT EXISTS division text;

ALTER TABLE public.work_types DROP CONSTRAINT IF EXISTS work_types_division_check;
ALTER TABLE public.work_types ADD CONSTRAINT work_types_division_check
  CHECK (division IS NULL OR division IN ('monolith', 'nvf_spk', 'general', 'hvac_water', 'electrical', 'finishing'));

