// Файл ВОР из «ВОРов и РД» годится для разбора, если это книга Excel (в старой категории vor бывают PDF и РД).
// Отдельный модуль без библиотеки Excel: проверку имени делают и реестр тендеров, и сервис расценки, которым
// сама библиотека не нужна.
export function isWorkbookFileName(name) {
  return /\.(xlsx|xlsm|xls)$/i.test(String(name || ''))
}

