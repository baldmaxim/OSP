-- «Договоры и ДС»: путь к Larix.CPM.
--
-- contracts.document_link («Ссылка на документ») у 225 из 327 договоров уже содержит ссылку на
-- карточку договора в Larix (cpm.su10.larix.ru/contract/…). С этой версии интерфейс показывает её как
-- «Путь к Larix.CPM» под номером договора — рядом с путём к папке и путём к Signal — и по её
-- заполненности определяет, внесён ли договор в Larix. Отдельная отметка (larix_entered и др.,
-- миграция 20260805) интерфейсом больше не читается и не пишется: одно значение — одно место.
-- Новых колонок нет, ссылки никуда не копируются — расходиться нечему.
--
-- Что меняет миграция:
--  1) У части договоров в document_link лежит не ссылка, а путь к сетевой папке — они числились бы
--     внесёнными в Larix. Поле очищается в двух случаях:
--       а) тот же путь уже записан в folder_path («Путь к папке») — значение ничего не теряет.
--          На копии от 12.10.2026 это ID портала 329, 332, 335, 347, 348; правило, а не список, чтобы
--          такие же строки, появившиеся до применения, тоже очистились;
--       б) ID портала 87, 91, 331, 334 — в folder_path у них другой путь, он остаётся как есть
--          (решение пользователя от 12.10.2026).
--     Настоящие ссылки (http/https) не трогаются. Не-ссылка, не подпавшая под «а» и «б», тоже
--     остаётся — её покажет проверка migration/backup/checks/20261012.sql (строка FAIL с ID).
--     Прежние значения — в резервной копии, снятой перед миграцией (migration/backup/backup.sh).
--  2) Комментарии к колонкам — чтобы назначение было видно в самой базе.
--
-- Строк не добавляет и не удаляет, структуру и права не меняет. Повтор безопасен: второй прогон
-- не находит строк под условие. Откат структуры не нужен; значения — из резервной копии.
BEGIN;
SET LOCAL lock_timeout = '10s';

UPDATE public.contracts
   SET document_link = NULL
 WHERE document_link IS NOT NULL
   AND document_link !~* '^\s*https?://'
   AND (
        btrim(document_link) = btrim(coalesce(folder_path, ''))
     OR display_id IN (87, 91, 331, 334)
   );

COMMENT ON COLUMN public.contracts.document_link IS
  'Путь к Larix.CPM: ссылка на карточку договора или ДС в Larix. Заполнено — документ внесён в Larix (состояние отдельно не хранится). Вносится в реестре под номером договора';
COMMENT ON COLUMN public.contracts.larix_entered IS
  'Не используется с 20261012: внесён ли договор в Larix, определяется по document_link';
COMMENT ON COLUMN public.contracts.larix_number IS
  'Не используется с 20261012 (номер в Larix не ведётся, путь — в document_link)';
COMMENT ON COLUMN public.contracts.larix_entered_at IS
  'Не используется с 20261012: правки пути к Larix.CPM — в contract_audit_log';
COMMENT ON COLUMN public.contracts.larix_entered_by IS
  'Не используется с 20261012: правки пути к Larix.CPM — в contract_audit_log';

COMMIT;
