-- Реестр «Договоры и ДС»: сумма генподряда и признак «ведёт наш отдел».
--
-- 1) Сумма генподряда.
--    contract_amount — сумма договора подряда (ДП), то, что мы платим подрядчику.
--    Рядом нужна сумма договора генподряда (ДГП) — то, что по тем же работам идёт
--    от заказчика. Наценка (генподрядный коэффициент) считается на лету как
--    ДГП / ДП и в базе не хранится: любое хранимое значение рано или поздно
--    разойдётся с суммами, из которых оно выведено.
--
-- 2) Признак «наш» договор.
--    Отдел ведёт не все договоры компании: часть лежит в реестре справочно.
--    Флаг разделяет реестр на «Все договоры» и «Наши договоры».
--    DEFAULT false: пока флаги не расставлены, «Наши договоры» будут пустыми —
--    это честнее, чем объявить своими все подряд.
--
-- Миграция идемпотентна.

ALTER TABLE contracts
  ADD COLUMN IF NOT EXISTS gp_amount NUMERIC(15, 2);

ALTER TABLE contracts
  ADD COLUMN IF NOT EXISTS handled_by_us BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN contracts.gp_amount IS
  'Сумма по договору генподряда (ДГП). Наценка = gp_amount / contract_amount, считается в UI';
COMMENT ON COLUMN contracts.handled_by_us IS
  'Договор ведёт наш отдел (ОСП). Разделяет реестр на «Все договоры» и «Наши договоры»';

-- Вкладка «Наши договоры» выбирается по флагу среди неудалённых.
CREATE INDEX IF NOT EXISTS idx_contracts_handled_by_us
  ON contracts(handled_by_us)
  WHERE deleted_at IS NULL;
