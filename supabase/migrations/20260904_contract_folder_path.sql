-- Договоры и ДС: путь к папке с документами в файловом хранилище.
--
-- Третий реестр с таким полем — после заявок на ДС (20260828) и тендеров
-- (20260903). Документы по договору лежат в общей сетевой папке, но путь к ней
-- нигде не хранился.
--
-- Открыть проводник по клику из браузера нельзя: Chrome и Edge блокируют переход
-- на file:// и на UNC-путь со страницы, загруженной по https. Поэтому путь в UI
-- показывается текстом с кнопкой «Копировать» — дальше человек вставляет его в
-- адресную строку проводника. Тип TEXT без CHECK: путь бывает и UNC
-- (\\server\share\...), и локальный (D:\...), и с любыми символами в именах папок.
--
-- Миграция идемпотентна.

ALTER TABLE contracts
  ADD COLUMN IF NOT EXISTS folder_path TEXT;

COMMENT ON COLUMN contracts.folder_path IS
  'Путь к папке с документами договора в файловом хранилище (UNC или локальный). Показывается для копирования: браузер не может открыть проводник по клику';
