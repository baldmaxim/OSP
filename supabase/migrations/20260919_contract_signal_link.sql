-- Договоры и ДС: путь к Signal — ссылка на документы договора в общем хранилище.
--
-- Показывается в колонке «Договор / № ДС» сразу после пути к папке. В отличие от
-- folder_path (миграция 20260904 — UNC-путь, который браузер открыть не может),
-- здесь обычно веб-ссылка: её открывают кликом. Если записан путь, а не ссылка,
-- интерфейс предлагает его скопировать. Поэтому тип TEXT без CHECK.
--
-- Миграция идемпотентна.

ALTER TABLE contracts
  ADD COLUMN IF NOT EXISTS signal_link TEXT;

COMMENT ON COLUMN contracts.signal_link IS
  'Путь к Signal: ссылка (или путь) на документы договора в общем хранилище. http(s) открывается кликом, прочее — копируется';
