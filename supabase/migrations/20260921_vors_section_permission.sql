-- Раздел прав «ВОРы и РД» (vors).
--
-- Страница «ВОРы и РД» раньше была частью раздела «Тендеры»: кто видел тендеры,
-- видел и её, а без тендеров — не видел. Сметно-техническому отделу нужен ровно
-- обратный набор: ВОРы и РД — рабочий раздел, а сами тендеры (участники, КП,
-- сравнение, документы) им закрыты.
--
-- Отдельный раздел в role_permissions позволяет настроить это в «Администрирование
-- → Права доступа»: у роли СТО «Тендеры» — выкл., «ВОРы и РД» — вкл.
--
-- Для существующих ролей копируем права раздела «Тендеры» — ничего не меняется:
-- кто работал с ВОРами через тендеры, продолжает. Повторный прогон ничего не
-- трогает (ON CONFLICT DO NOTHING), ручные настройки администратора сохраняются.

INSERT INTO role_permissions (role, section, can_view, can_edit)
SELECT rp.role, 'vors', rp.can_view, rp.can_edit
FROM role_permissions rp
WHERE rp.section = 'tenders'
ON CONFLICT (role, section) DO NOTHING;
