-- Реестр расценок: поиск по наименованию (ilike '%...%') по дедуп-вью
-- kp_rates_registry / supply_rates_registry на больших объёмах данных упирался в
-- statement_timeout (Postgres 57014 → «Ошибка загрузки: слишком большой объём
-- данных для подсчёта»). Результат запроса небольшой (несколько строк), но дедуп
-- с нормализацией наименований (DISTINCT ON + kp_norm_name) сканирует всю базу
-- расценок — на это нужно чуть больше времени, чем даёт дефолтный лимит роли.
--
-- Поднимаем лимит времени для роли authenticated (через неё ходит PostgREST для
-- залогиненных пользователей). 30 c — потолок для тяжёлых аналитических запросов
-- реестра; обычные запросы завершаются за миллисекунды и лимита не касаются.
--
-- ВАЖНО: настройка применяется к НОВЫМ соединениям пула PostgREST. Чтобы вступила
-- в силу сразу — перезапустите проект (Dashboard → Settings → General →
-- Restart project) либо дождитесь пересоздания соединений пула.
--
-- Откат при необходимости:
--   alter role authenticated set statement_timeout = '8s';

alter role authenticated set statement_timeout = '30s';

-- Подсказать PostgREST перечитать конфигурацию.
notify pgrst, 'reload config';
