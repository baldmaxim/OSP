-- «Тендеры (прочее)»: наименование объекта своими словами, без привязки к реестру.
--
-- Направление «прочее» (миграция 20260820) заводится под закупки и работы, для
-- которых стройплощадки в реестре объектов нет и заводить её не нужно: разовый
-- подрядчик, общехозяйственная закупка, офисное помещение. Раньше выбор был
-- бинарным — либо существующий объект, либо ничего.
--
-- Теперь можно либо выбрать объект из реестра (object_id, как прежде), либо
-- вписать наименование вручную (custom_object_name). Вписанное имя живёт ТОЛЬКО
-- в самом тендере: в таблицу objects ничего не добавляется, в разделе «Объекты»
-- такие названия не появляются.
--
-- Одновременно оба поля не заполняются: интерфейс при выборе объекта из реестра
-- очищает ручное имя, и наоборот. На уровне БД жёстко не запрещаем — данные из
-- импорта и правки через API не должны падать из-за этого.
--
-- Миграция идемпотентна.

ALTER TABLE tenders
  ADD COLUMN IF NOT EXISTS custom_object_name TEXT;

COMMENT ON COLUMN tenders.custom_object_name IS
  'Наименование объекта, вписанное вручную (направление «прочее»). Используется, когда object_id пуст; в реестр objects не попадает';

-- Поиск по названию идёт и по ручному имени тоже.
CREATE INDEX IF NOT EXISTS idx_tenders_custom_object_name
  ON tenders(custom_object_name)
  WHERE custom_object_name IS NOT NULL;
