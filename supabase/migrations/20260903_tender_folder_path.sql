-- Тендеры: путь к папке с документами в файловом хранилище.
--
-- То же, что сделано для заявок на ДС (миграция 20260828): документы по тендеру
-- лежат в общей сетевой папке, но путь к ней нигде не хранился — его передавали
-- на словах и в переписке.
--
-- Открыть проводник по клику из браузера нельзя: Chrome и Edge блокируют переход
-- на file:// и на UNC-путь со страницы, загруженной по https. Поэтому путь в UI
-- показывается текстом с кнопкой «Копировать» — дальше человек вставляет его в
-- адресную строку проводника. Тип TEXT без CHECK: путь бывает и UNC
-- (\\server\share\...), и локальный (D:\...), и с любыми символами в именах папок.
--
-- Миграция идемпотентна.

ALTER TABLE tenders
  ADD COLUMN IF NOT EXISTS folder_path TEXT;

COMMENT ON COLUMN tenders.folder_path IS
  'Путь к папке с документами тендера в файловом хранилище (UNC или локальный). Показывается для копирования: браузер не может открыть проводник по клику';
