-- Заявки на ДС: путь к папке с документами в файловом хранилище.
--
-- Документы по ДС лежат в общей сетевой папке, но путь к ней нигде не хранился —
-- его передавали на словах и в переписке. Теперь он записан в самой заявке.
--
-- Открыть проводник по клику из браузера нельзя: Chrome и Edge блокируют переход
-- на file:// и на UNC-путь со страницы, загруженной по https. Поэтому путь в UI
-- показывается текстом с кнопкой «Копировать» — дальше человек вставляет его в
-- адресную строку проводника. Тип TEXT без CHECK: путь бывает и UNC
-- (\\server\share\...), и локальный (D:\...), и с любыми символами в именах папок.
--
-- Миграция идемпотентна.

ALTER TABLE dc_requests
  ADD COLUMN IF NOT EXISTS folder_path TEXT;

COMMENT ON COLUMN dc_requests.folder_path IS
  'Путь к папке с документами в файловом хранилище (UNC или локальный). Показывается для копирования: браузер не может открыть проводник по клику';
