-- «Реестр по договорам» для сотрудников объекта (решение пользователя 10.11.2026): руководитель строительства и экономист
-- объекта видят реестр договоров только своих объектов, подают из него заявку на заключение ДП («+ Заявка на заключение ДП»
-- у вкладки «Все»), договоры не заводят.
--
-- Что сводит страница (ContractsPage, siteStaff): договоры и фильтр объектов — только объекты вошедшего (user_roles.object_ids,
-- как было у руководителя строительства с 07.05), без общей папки раздела, «Структуры хранения» и «Стандартных приложений».
-- Здесь — только права ролей: «Договоры» — просмотр без правки. У руководителя строительства так и было (20260507), экономисту
-- объекта просмотр раньше не выдавали: реестр ему был закрыт. Роли нет в справочнике — строка не заводится. Дальше — галочками
-- в «Правах доступа». Правила по строкам и данные не меняются. Повтор безопасен.
--
-- Не в tests/db/baseline/candidate-migrations.txt: права классов test:db (правила по строкам) не меняются, а на слепке схемы
-- без данных справочник ролей пуст — проверке migration/backup/checks/20270106.sql там нечего проверять. На копии прода она
-- отвечает FAIL до миграции и OK после.
BEGIN;

INSERT INTO public.role_permissions (role, section, can_view, can_edit)
SELECT r.key, 'contracts', true, false
FROM public.roles r
WHERE r.key IN ('construction_manager', 'economist_object')
ON CONFLICT (role, section) DO UPDATE SET can_view = true, can_edit = false;

COMMIT;
